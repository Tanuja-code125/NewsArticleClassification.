# ============================================================
# NEWS CLASSIFICATION USING NLP AND MACHINE LEARNING
# Models: Naive Bayes, Logistic Regression, Linear SVM
# ============================================================

import os
import re
import time
import joblib
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.naive_bayes import MultinomialNB
from sklearn.linear_model import LogisticRegression
from sklearn.svm import LinearSVC

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    ConfusionMatrixDisplay
)

# ============================================================
# 1. CONFIGURATION
# ============================================================

DATASET_PATH ="dataset/News.csv"
RESULTS_DIR = "results"

os.makedirs(RESULTS_DIR, exist_ok=True)

# ============================================================
# 2. LOAD DATASET
# ============================================================

if not os.path.exists(DATASET_PATH):
    raise FileNotFoundError(
        f"Dataset not found: {DATASET_PATH}\n"
        "Place News.csv inside the dataset folder."
    )

df = pd.read_csv(DATASET_PATH, low_memory=False)

# Remove extra spaces and normalize column names
df.columns = df.columns.astype(str).str.strip()

print("\n========== DATASET INFORMATION ==========")
print("Original rows:", len(df))
print("Columns:", df.columns.tolist())

# Match column names regardless of capitalization
column_map = {
    str(col).strip().lower(): col
    for col in df.columns
}

# ============================================================
# 3. DETECT TARGET CATEGORY COLUMN
# ============================================================

# Priority depends on the intended classification task.
# If your dataset has a Category column, it is preferred.
category_options = [
    "category",
    "news_category",
    "news category",
    "label",
    "labels",
    "class",
    "target",
    "subject",
    "type"
]

category_col = next(
    (
        column_map[name]
        for name in category_options
        if name in column_map
    ),
    None
)

if category_col is None:
    raise ValueError(
        "Could not detect the target category column.\n"
        f"Available columns: {df.columns.tolist()}\n"
        "Set category_col manually in Section 3."
    )

# ============================================================
# 4. DETECT NEWS TEXT COLUMNS
# ============================================================

# Combine title and article text when both are available.
# This preserves useful information from both fields.

text_options = [
    "text",
    "full_text",
    "article_text",
    "content",
    "news",
    "article",
    "description",
    "body"
]

title_options = [
    "title",
    "headline",
    "news_title"
]

text_cols = [
    column_map[name]
    for name in text_options
    if name in column_map
]

title_cols = [
    column_map[name]
    for name in title_options
    if name in column_map
]

# If there is no article-text column, use the title.
if not text_cols and not title_cols:
    raise ValueError(
        "Could not detect news text columns.\n"
        f"Available columns: {df.columns.tolist()}"
    )

# Exclude columns that contain labels, dates or metadata.
selected_cols = list(dict.fromkeys(title_cols + text_cols))

print("Target column:", category_col)
print("Text columns:", selected_cols)

# ============================================================
# 5. PREPARE DATA
# ============================================================

data = df[selected_cols + [category_col]].copy()

# Remove rows with missing target labels
data = data.dropna(subset=[category_col])

# Convert target labels to strings
data["category"] = (
    data[category_col]
    .astype(str)
    .str.strip()
)

# Combine available title and article text
def combine_news(row):
    parts = []

    for col in selected_cols:
        value = row[col]

        if pd.notna(value):
            value = str(value).strip()

            if value and value.lower() not in {
                "nan", "none", "null"
            }:
                parts.append(value)

    # Avoid adding a title twice if it is identical
    # to the article text.
    unique_parts = list(dict.fromkeys(parts))

    return " ".join(unique_parts)


data["news_text"] = data.apply(combine_news, axis=1)

data = data[
    (data["news_text"].str.strip() != "") &
    (data["category"] != "")
].copy()

# ============================================================
# 6. CLEAN NEWS TEXT
# ============================================================

def clean_text(text):
    text = str(text).lower()

    # Remove URLs
    text = re.sub(
        r"(?:https?://|www\.)\S+",
        " ",
        text
    )

    # Remove HTML tags
    text = re.sub(r"<[^>]+>", " ", text)

    # Keep alphabetic words and spaces
    text = re.sub(r"[^a-z\s]", " ", text)

    # Remove extra whitespace
    text = re.sub(r"\s+", " ", text)

    return text.strip()


data["clean_text"] = data["news_text"].apply(clean_text)

data = data[data["clean_text"] != ""].copy()

# ============================================================
# 7. REMOVE DUPLICATE ARTICLES
# ============================================================

before_duplicates = len(data)

# Remove exact duplicate cleaned articles.
# If identical article text has conflicting labels,
# remove those ambiguous articles as well.

label_counts = data.groupby(
    "clean_text"
)["category"].nunique()

ambiguous_texts = label_counts[
    label_counts > 1
].index

data = data[
    ~data["clean_text"].isin(ambiguous_texts)
].copy()

data = data.drop_duplicates(
    subset=["clean_text"],
    keep="first"
)

print("\n========== PREPROCESSING RESULTS ==========")
print("Rows before duplicate removal:", before_duplicates)
print("Rows after cleaning:", len(data))
print("Duplicate/conflicting articles removed:",
      before_duplicates - len(data))
print("Unique articles:", data["clean_text"].nunique())
print("Number of categories:", data["category"].nunique())

print("\nCategory distribution:")
print(data["category"].value_counts())

# ============================================================
# 8. PREPARE INPUT AND OUTPUT
# ============================================================

X = data["clean_text"]
y = data["category"]

if y.nunique() < 2:
    raise ValueError(
        "At least two different categories are required."
    )

class_counts = y.value_counts()

if class_counts.min() < 2:
    raise ValueError(
        "At least one category has fewer than 2 articles.\n"
        "More samples are required for a stratified split."
    )

# Make sure the test set can contain every category.
test_count = max(
    int(round(len(data) * 0.20)),
    y.nunique()
)

train_count = len(data) - test_count

if train_count < y.nunique():
    raise ValueError(
        "Not enough data for training and testing "
        "with all categories represented."
    )

# ============================================================
# 9. SPLIT DATASET
# ============================================================

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=test_count,
    random_state=42,
    stratify=y
)

print("\n========== TRAIN TEST SPLIT ==========")
print("Total articles:", len(data))
print("Training articles:", len(X_train))
print("Testing articles:", len(X_test))

# ============================================================
# 10. DEFINE MACHINE LEARNING MODELS
# ============================================================

models = {
    "Naive Bayes": MultinomialNB(),

    "Logistic Regression": LogisticRegression(
        max_iter=2000,
        random_state=42
    ),

    "Linear SVM": LinearSVC(
        random_state=42
    )
}

results = []
trained_models = {}

# ============================================================
# 11. TRAIN AND EVALUATE MODELS
# ============================================================

for name, classifier in models.items():

    print("\n" + "=" * 55)
    print(name)
    print("=" * 55)

    model = Pipeline([
        (
            "tfidf",
            TfidfVectorizer(
                max_features=20000,
                ngram_range=(1, 2),
                stop_words="english",
                sublinear_tf=True
            )
        ),
        ("classifier", classifier)
    ])

    start_time = time.time()

    # Fit TF-IDF and classifier using training data only
    model.fit(X_train, y_train)

    training_time = time.time() - start_time

    # Predict unseen test articles
    predictions = model.predict(X_test)

    # Evaluation metrics
    accuracy = accuracy_score(y_test, predictions)

    precision = precision_score(
        y_test,
        predictions,
        average="weighted",
        zero_division=0
    )

    recall = recall_score(
        y_test,
        predictions,
        average="weighted",
        zero_division=0
    )

    f1 = f1_score(
        y_test,
        predictions,
        average="weighted",
        zero_division=0
    )

    results.append({
        "Model": name,
        "Accuracy (%)": round(accuracy * 100, 2),
        "Precision (%)": round(precision * 100, 2),
        "Recall (%)": round(recall * 100, 2),
        "F1 Score (%)": round(f1 * 100, 2),
        "Training Time (seconds)": round(training_time, 3)
    })

    trained_models[name] = model

    print(f"Accuracy:  {accuracy * 100:.2f}%")
    print(f"Precision: {precision * 100:.2f}%")
    print(f"Recall:    {recall * 100:.2f}%")
    print(f"F1 Score:  {f1 * 100:.2f}%")

    print("\nClassification Report:")
    print(
        classification_report(
            y_test,
            predictions,
            zero_division=0
        )
    )

    # Save confusion matrix
    display = ConfusionMatrixDisplay.from_predictions(
        y_test,
        predictions,
        labels=sorted(y.unique()),
        xticks_rotation="vertical"
    )

    display.ax_.set_title(
        f"{name} Confusion Matrix"
    )

    display.figure_.tight_layout()

    filename = name.lower().replace(" ", "_")

    display.figure_.savefig(
        os.path.join(
            RESULTS_DIR,
            f"{filename}_confusion_matrix.png"
        ),
        dpi=150,
        bbox_inches="tight"
    )

    plt.close(display.figure_)

# ============================================================
# 12. COMPARE MODELS
# ============================================================

results_df = pd.DataFrame(results)

results_df = results_df.sort_values(
    by="F1 Score (%)",
    ascending=False
).reset_index(drop=True)

print("\n========== MODEL COMPARISON ==========")
print(results_df.to_string(index=False))

results_df.to_csv(
    os.path.join(
        RESULTS_DIR,
        "model_comparison.csv"
    ),
    index=False
)

# ============================================================
# 13. CREATE COMPARISON GRAPH
# ============================================================

results_df.set_index("Model")[
    [
        "Accuracy (%)",
        "Precision (%)",
        "Recall (%)",
        "F1 Score (%)"
    ]
].plot(
    kind="bar",
    figsize=(11, 6)
)

plt.title("News Classification Model Comparison")
plt.ylabel("Score (%)")
plt.xlabel("Machine Learning Model")
plt.ylim(0, 105)
plt.xticks(rotation=15)
plt.tight_layout()

plt.savefig(
    os.path.join(
        RESULTS_DIR,
        "model_comparison.png"
    ),
    dpi=150,
    bbox_inches="tight"
)

plt.close()

# ============================================================
# 14. SAVE BEST MODEL
# ============================================================

best_name = results_df.iloc[0]["Model"]
best_model = trained_models[best_name]

joblib.dump(
    best_model,
    os.path.join(
        RESULTS_DIR,
        "best_news_model.joblib"
    )
)

# Save metadata for later prediction
metadata = {
    "target_column": category_col,
    "text_columns": selected_cols,
    "categories": sorted(y.unique()),
    "best_model": best_name
}

joblib.dump(
    metadata,
    os.path.join(
        RESULTS_DIR,
        "model_metadata.joblib"
    )
)

# ============================================================
# 15. PROJECT SUMMARY
# ============================================================

print("\n========== PROJECT COMPLETED ==========")
print("Dataset:", DATASET_PATH)
print("Best model based on weighted F1 score:", best_name)
print("Results folder:", RESULTS_DIR)
print("Comparison table: results/model_comparison.csv")
print("Comparison graph: results/model_comparison.png")
print("Best model: results/best_news_model.joblib")
print("Model metadata: results/model_metadata.joblib")
print("Confusion matrices saved for all three models.")